CREATE TABLE job_listing (
                             id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             title character varying(255) NOT NULL,
                             url character varying(1080) NOT NULL,
                             modality character varying(255),
                             source character varying(255) NOT NULL,
                             status character varying(255) NOT NULL,
                             company character varying(255) NOT NULL,
                             description text NOT NULL,
                             salary_text character varying(255),
                             first_seen_date timestamp(6) with time zone NOT NULL,
                             posted_date date,
                             salary_max integer,
                             salary_min integer,
                             CONSTRAINT uk_job_listing_url UNIQUE (url),
                             CONSTRAINT job_listing_modality_check
                                 CHECK (modality IN ('OFFICE', 'HYBRID', 'REMOTE')),
                             CONSTRAINT job_listing_source_check
                                 CHECK (source IN ('TECNOEMPLEO', 'INFOJOBS')),
                             CONSTRAINT job_listing_status_check
                                 CHECK (status IN ('NEW', 'INTERESTED', 'APPLIED', 'REJECTED'))
);